//! Accounts are created at the identity provider. This installation keeps the
//! provider subject, the generated username and encrypted personal fields.
use axum::{
    Json,
    extract::{Path, State},
    http::{HeaderMap, StatusCode},
    response::IntoResponse,
};
use chrono::{DateTime, NaiveDate, Utc};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::personal_data::Field;
use crate::state::SharedState;

type ApiError = (StatusCode, String);

#[derive(Serialize, schemars::JsonSchema)]
pub struct UserResponse {
    pub id: Uuid,
    /// Generated by the identity provider; carries no personal data.
    pub username: Option<String>,
    pub display_name: Option<String>,
    pub date_of_birth: Option<NaiveDate>,
    pub pcd_status: Option<bool>,
    pub role: String,
    pub created_at: Option<DateTime<Utc>>,
}

/// Self-declared eligibility for reserved spots; `null` clears a declaration.
#[derive(Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct UpdateEligibility {
    pub date_of_birth: Option<NaiveDate>,
    pub pcd_status: Option<bool>,
}

fn failed() -> ApiError {
    (
        StatusCode::INTERNAL_SERVER_ERROR,
        "Failed to fetch user".to_string(),
    )
}

async fn load(state: &SharedState, id: Uuid) -> Result<UserResponse, ApiError> {
    let record = sqlx::query!(
        r#"
        SELECT
        id,
        username,
        display_name_enc,
        date_of_birth_enc,
        pcd_status_enc,
        role as "role!",
        created_at as "created_at?"
        FROM users
        WHERE id = $1
        "#,
        id
    )
    .fetch_optional(state.installation.pool())
    .await
    .map_err(|e| {
        tracing::error!("Database error: {}", e);
        failed()
    })?
    .ok_or_else(|| (StatusCode::NOT_FOUND, "User not found".to_string()))?;

    let cipher = &state.personal_data;
    let decrypted = cipher
        .decrypt_optional::<String>(
            Field::UserDisplayName,
            record.id,
            record.display_name_enc.as_deref(),
        )
        .and_then(|name| {
            let born = cipher.decrypt_optional(
                Field::UserDateOfBirth,
                record.id,
                record.date_of_birth_enc.as_deref(),
            )?;
            let pcd = cipher.decrypt_optional(
                Field::UserPcdStatus,
                record.id,
                record.pcd_status_enc.as_deref(),
            )?;
            Ok((name, born, pcd))
        });
    let (display_name, date_of_birth, pcd_status) = decrypted.map_err(|error| {
        tracing::error!(%error, "Stored personal data cannot be decrypted");
        failed()
    })?;
    Ok(UserResponse {
        id: record.id,
        username: record.username,
        display_name,
        date_of_birth,
        pcd_status,
        role: record.role,
        created_at: record.created_at,
    })
}

pub async fn get_user(
    State(state): State<SharedState>,
    Path(id): Path<Uuid>,
    headers: HeaderMap,
) -> Result<impl IntoResponse, ApiError> {
    let requester = crate::security::authenticated_session(
        &headers,
        &state.jwt_secret,
        state.installation.pool(),
    )
    .await?;
    if requester.role != "admin" && requester.user_id != id {
        return Err((StatusCode::FORBIDDEN, "User access denied".to_string()));
    }
    let user = load(&state, id).await?;
    if requester.user_id != id {
        // An administrator read someone else's personal data.
        crate::audit::record(
            state.installation.pool(),
            requester.user_id,
            "user_read",
            Some(&id.to_string()),
            serde_json::json!({}),
        )
        .await
        .map_err(|error| {
            tracing::error!(%error, "Audit record failed");
            failed()
        })?;
    }
    Ok((StatusCode::OK, Json(user)))
}

/// The signed-in account; apps call it after the sign-in redirect.
pub async fn me(
    State(state): State<SharedState>,
    headers: HeaderMap,
) -> Result<impl IntoResponse, ApiError> {
    let requester =
        crate::security::authenticated_user(&headers, &state.jwt_secret, state.installation.pool())
            .await?;
    Ok((StatusCode::OK, Json(load(&state, requester).await?)))
}

pub async fn update_eligibility(
    State(state): State<SharedState>,
    headers: HeaderMap,
    Json(declared): Json<UpdateEligibility>,
) -> Result<impl IntoResponse, ApiError> {
    let requester =
        crate::security::authenticated_user(&headers, &state.jwt_secret, state.installation.pool())
            .await?;
    let cipher = &state.personal_data;
    let encrypted = cipher
        .encrypt(Field::UserDateOfBirth, requester, &declared.date_of_birth)
        .and_then(|born| {
            let pcd = cipher.encrypt(Field::UserPcdStatus, requester, &declared.pcd_status)?;
            Ok((born, pcd))
        });
    let (born, pcd) = encrypted.map_err(|error| {
        tracing::error!(%error, "Eligibility encryption failed");
        failed()
    })?;
    sqlx::query("UPDATE users SET date_of_birth_enc = $2, pcd_status_enc = $3 WHERE id = $1")
        .bind(requester)
        .bind(born)
        .bind(pcd)
        .execute(state.installation.pool())
        .await
        .map_err(|error| {
            tracing::error!(%error, "Eligibility update failed");
            failed()
        })?;
    Ok((StatusCode::OK, Json(load(&state, requester).await?)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn eligibility_accepts_declared_and_cleared_values_only() {
        let parsed: UpdateEligibility =
            serde_json::from_str(r#"{"date_of_birth":"1950-01-02","pcd_status":null}"#).unwrap();
        assert_eq!(parsed.date_of_birth, NaiveDate::from_ymd_opt(1950, 1, 2));
        assert_eq!(parsed.pcd_status, None);
        for rejected in [
            r#"{"date_of_birth":null,"pcd_status":true,"email":"x@example.com"}"#,
            r#"{"date_of_birth":"not-a-date","pcd_status":true}"#,
        ] {
            assert!(serde_json::from_str::<UpdateEligibility>(rejected).is_err());
        }
    }

    #[test]
    fn user_response_never_carries_an_email() {
        let response = UserResponse {
            id: Uuid::nil(),
            username: Some("ea-7k3m9qx2vd".into()),
            display_name: Some("Maria".into()),
            date_of_birth: None,
            pcd_status: None,
            role: "admin".to_string(),
            created_at: None,
        };
        let json = serde_json::to_value(&response).unwrap();
        assert_eq!(json["username"], "ea-7k3m9qx2vd");
        assert!(json.get("email").is_none());
    }
}

#[derive(Serialize, sqlx::FromRow, schemars::JsonSchema)]
pub struct ExportedReservation {
    pub id: Uuid,
    pub spot_id: String,
    pub status: String,
    pub created_at: Option<DateTime<Utc>>,
    pub expires_at: DateTime<Utc>,
    pub completed_at: Option<DateTime<Utc>>,
}

#[derive(Serialize, sqlx::FromRow, schemars::JsonSchema)]
pub struct ExportedVisit {
    pub spot_id: String,
    pub occupied_at: DateTime<Utc>,
    pub released_at: Option<DateTime<Utc>>,
}

#[derive(Serialize, sqlx::FromRow, schemars::JsonSchema)]
pub struct ExportedSession {
    pub created_at: DateTime<Utc>,
    pub expires_at: DateTime<Utc>,
    pub revoked_at: Option<DateTime<Utc>>,
}

/// Everything this installation keeps about the signed-in person, decrypted.
/// E-mail and password live only at the identity provider.
#[derive(Serialize, schemars::JsonSchema)]
pub struct PersonalDataExport {
    pub account: UserResponse,
    pub reservations: Vec<ExportedReservation>,
    pub occupancy_history: Vec<ExportedVisit>,
    pub sessions: Vec<ExportedSession>,
}

fn storage_error(error: sqlx::Error) -> ApiError {
    tracing::error!(%error, "Personal data request failed");
    (
        StatusCode::SERVICE_UNAVAILABLE,
        "Personal data temporarily unavailable".to_string(),
    )
}

pub async fn export_personal_data(
    State(state): State<SharedState>,
    headers: HeaderMap,
) -> Result<impl IntoResponse, ApiError> {
    let requester =
        crate::security::authenticated_user(&headers, &state.jwt_secret, state.installation.pool())
            .await?;
    let pool = state.installation.pool();
    let account = load(&state, requester).await?;
    let reservations = sqlx::query_as(
        "SELECT id, spot_id, status, created_at, expires_at, completed_at \
         FROM reservations WHERE user_id = $1 ORDER BY created_at",
    )
    .bind(requester)
    .fetch_all(pool)
    .await
    .map_err(storage_error)?;
    let occupancy_history = sqlx::query_as(
        "SELECT spot_id, occupied_at, released_at FROM user_occupancy_history \
         WHERE user_id = $1 ORDER BY occupied_at",
    )
    .bind(requester)
    .fetch_all(pool)
    .await
    .map_err(storage_error)?;
    let sessions = sqlx::query_as(
        "SELECT created_at, expires_at, revoked_at FROM auth_sessions \
         WHERE user_id = $1 ORDER BY created_at",
    )
    .bind(requester)
    .fetch_all(pool)
    .await
    .map_err(storage_error)?;
    Ok((
        StatusCode::OK,
        [(axum::http::header::CACHE_CONTROL, "no-store")],
        Json(PersonalDataExport {
            account,
            reservations,
            occupancy_history,
            sessions,
        }),
    ))
}

/// Deletes this installation's account of the signed-in person: active
/// reservations release their spots, and sessions, tickets, reservations and
/// parking history go with the account. The identity provider account is
/// removed separately (tools/identity/provision.py).
pub async fn delete_account(
    State(state): State<SharedState>,
    headers: HeaderMap,
) -> Result<impl IntoResponse, ApiError> {
    let requester =
        crate::security::authenticated_user(&headers, &state.jwt_secret, state.installation.pool())
            .await?;
    let mut tx = state
        .installation
        .pool()
        .begin()
        .await
        .map_err(storage_error)?;
    sqlx::query("SELECT id FROM users WHERE id = $1 FOR UPDATE")
        .bind(requester)
        .execute(&mut *tx)
        .await
        .map_err(storage_error)?;
    let released: Vec<String> = sqlx::query_scalar(
        "UPDATE spots SET status = 'free', last_updated = NOW() WHERE status = 'reserved' \
         AND id IN (SELECT spot_id FROM reservations WHERE user_id = $1 AND status = 'active') \
         RETURNING id",
    )
    .bind(requester)
    .fetch_all(&mut *tx)
    .await
    .map_err(storage_error)?;
    // Sessions, tickets, reservations and history cascade with the account.
    sqlx::query("DELETE FROM users WHERE id = $1")
        .bind(requester)
        .execute(&mut *tx)
        .await
        .map_err(storage_error)?;
    tx.commit().await.map_err(storage_error)?;
    for spot_id in released {
        let update = crate::ws::messages::ServerToAppMsg::SpotUpdate {
            spot_id,
            status: "free".to_owned(),
        };
        if let Ok(json) = serde_json::to_string(&update) {
            let _ = state.installation.tx.send(json);
        }
    }
    Ok((
        StatusCode::NO_CONTENT,
        [
            (
                axum::http::header::SET_COOKIE,
                crate::security::clear_session_cookie(),
            ),
            (axum::http::header::CACHE_CONTROL, "no-store"),
        ],
    ))
}
