//! Accounts are created at the identity provider. This installation keeps the
//! provider subject, the generated username and encrypted personal fields.
use axum::{
    Json,
    extract::{Path, State},
    http::{HeaderMap, StatusCode},
    response::IntoResponse,
};
use chrono::{DateTime, NaiveDate, Utc};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::personal_data::Field;
use crate::state::SharedState;

type ApiError = (StatusCode, String);

#[derive(Serialize, schemars::JsonSchema)]
pub struct UserResponse {
    pub id: Uuid,
    /// Generated by the identity provider; carries no personal data.
    pub username: Option<String>,
    pub display_name: Option<String>,
    pub date_of_birth: Option<NaiveDate>,
    pub pcd_status: Option<bool>,
    pub role: String,
    pub created_at: Option<DateTime<Utc>>,
}

/// Self-declared eligibility for reserved spots; `null` clears a declaration.
#[derive(Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct UpdateEligibility {
    pub date_of_birth: Option<NaiveDate>,
    pub pcd_status: Option<bool>,
}

fn failed() -> ApiError {
    (
        StatusCode::INTERNAL_SERVER_ERROR,
        "Failed to fetch user".to_string(),
    )
}

async fn load(state: &SharedState, id: Uuid) -> Result<UserResponse, ApiError> {
    let record = sqlx::query!(
        r#"
        SELECT
        id,
        username,
        display_name_enc,
        date_of_birth_enc,
        pcd_status_enc,
        role as "role!",
        created_at as "created_at?"
        FROM users
        WHERE id = $1
        "#,
        id
    )
    .fetch_optional(state.installation.pool())
    .await
    .map_err(|e| {
        tracing::error!("Database error: {}", e);
        failed()
    })?
    .ok_or_else(|| (StatusCode::NOT_FOUND, "User not found".to_string()))?;

    let cipher = &state.personal_data;
    let decrypted = cipher
        .decrypt_optional::<String>(
            Field::UserDisplayName,
            record.id,
            record.display_name_enc.as_deref(),
        )
        .and_then(|name| {
            let born = cipher.decrypt_optional(
                Field::UserDateOfBirth,
                record.id,
                record.date_of_birth_enc.as_deref(),
            )?;
            let pcd = cipher.decrypt_optional(
                Field::UserPcdStatus,
                record.id,
                record.pcd_status_enc.as_deref(),
            )?;
            Ok((name, born, pcd))
        });
    let (display_name, date_of_birth, pcd_status) = decrypted.map_err(|error| {
        tracing::error!(%error, "Stored personal data cannot be decrypted");
        failed()
    })?;
    Ok(UserResponse {
        id: record.id,
        username: record.username,
        display_name,
        date_of_birth,
        pcd_status,
        role: record.role,
        created_at: record.created_at,
    })
}

pub async fn get_user(
    State(state): State<SharedState>,
    Path(id): Path<Uuid>,
    headers: HeaderMap,
) -> Result<impl IntoResponse, ApiError> {
    let requester = crate::security::authenticated_session(
        &headers,
        &state.jwt_secret,
        state.installation.pool(),
    )
    .await?;
    if requester.role != "admin" && requester.user_id != id {
        return Err((StatusCode::FORBIDDEN, "User access denied".to_string()));
    }
    Ok((StatusCode::OK, Json(load(&state, id).await?)))
}

/// The signed-in account; apps call it after the sign-in redirect.
pub async fn me(
    State(state): State<SharedState>,
    headers: HeaderMap,
) -> Result<impl IntoResponse, ApiError> {
    let requester =
        crate::security::authenticated_user(&headers, &state.jwt_secret, state.installation.pool())
            .await?;
    Ok((StatusCode::OK, Json(load(&state, requester).await?)))
}

pub async fn update_eligibility(
    State(state): State<SharedState>,
    headers: HeaderMap,
    Json(declared): Json<UpdateEligibility>,
) -> Result<impl IntoResponse, ApiError> {
    let requester =
        crate::security::authenticated_user(&headers, &state.jwt_secret, state.installation.pool())
            .await?;
    let cipher = &state.personal_data;
    let encrypted = cipher
        .encrypt(Field::UserDateOfBirth, requester, &declared.date_of_birth)
        .and_then(|born| {
            let pcd = cipher.encrypt(Field::UserPcdStatus, requester, &declared.pcd_status)?;
            Ok((born, pcd))
        });
    let (born, pcd) = encrypted.map_err(|error| {
        tracing::error!(%error, "Eligibility encryption failed");
        failed()
    })?;
    sqlx::query("UPDATE users SET date_of_birth_enc = $2, pcd_status_enc = $3 WHERE id = $1")
        .bind(requester)
        .bind(born)
        .bind(pcd)
        .execute(state.installation.pool())
        .await
        .map_err(|error| {
            tracing::error!(%error, "Eligibility update failed");
            failed()
        })?;
    Ok((StatusCode::OK, Json(load(&state, requester).await?)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn eligibility_accepts_declared_and_cleared_values_only() {
        let parsed: UpdateEligibility =
            serde_json::from_str(r#"{"date_of_birth":"1950-01-02","pcd_status":null}"#).unwrap();
        assert_eq!(parsed.date_of_birth, NaiveDate::from_ymd_opt(1950, 1, 2));
        assert_eq!(parsed.pcd_status, None);
        for rejected in [
            r#"{"date_of_birth":null,"pcd_status":true,"email":"x@example.com"}"#,
            r#"{"date_of_birth":"not-a-date","pcd_status":true}"#,
        ] {
            assert!(serde_json::from_str::<UpdateEligibility>(rejected).is_err());
        }
    }

    #[test]
    fn user_response_never_carries_an_email() {
        let response = UserResponse {
            id: Uuid::nil(),
            username: Some("ea-7k3m9qx2vd".into()),
            display_name: Some("Maria".into()),
            date_of_birth: None,
            pcd_status: None,
            role: "admin".to_string(),
            created_at: None,
        };
        let json = serde_json::to_value(&response).unwrap();
        assert_eq!(json["username"], "ea-7k3m9qx2vd");
        assert!(json.get("email").is_none());
    }
}
